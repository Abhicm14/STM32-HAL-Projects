void OLED_Set_Cursor(uint8_t x, uint8_t y)
{
    OLED_Send_Command(0xB0 + y);
    OLED_Send_Command(((x & 0xF0) >> 4) | 0x10);
    OLED_Send_Command((x & 0x0F) | 0x01);
}

void OLED_Clear(void)
{
    for (uint8_t page = 0; page < 8; page++) {
        OLED_Set_Cursor(0, page);
        for (uint8_t col = 0; col < 128; col++) {
            OLED_Send_Data(0x00);
        }
    }
}

void OLED_Send_Char(char ch)
{
    if (ch < 32 || ch > 126) ch = '?';
    for (int i = 0; i < OLED_EXP_CHAR_LENGTH; i++) {
        OLED_Send_Data(asciiTable[ch - 32][i]);
    }
}

void OLED_Send_String(const char *str)
{
    while (*str) {
        OLED_Send_Char(*str++);
    }
}

void OLED_Send_Integer(int value)
{
    char buffer[16];
    sprintf(buffer, "%d", value);
    OLED_Send_String(buffer);
}

void OLED_Send_Float(float num, int precision)
{
    char buffer[16];
    char format[10];
    sprintf(format, "%%.%df", precision);
    sprintf(buffer, format, num);
    OLED_Send_String(buffer);
}

void OLED_Draw_Bitmap(const uint8_t *bitmap, uint8_t width, uint8_t height)
{
    uint8_t pages = height / 8;
    for (uint8_t page = 0; page < pages; page++) {
        OLED_Set_Cursor(0, page);
        for (uint8_t col = 0; col < width; col++) {
            OLED_Send_Data(bitmap[page * width + col]);
        }
    }
}
