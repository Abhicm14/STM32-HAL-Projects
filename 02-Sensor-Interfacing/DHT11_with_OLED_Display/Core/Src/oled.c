static void OLED_Write(uint8_t value, uint8_t cmd_type)
{
    uint8_t data[2];
    data[0] = cmd_type;
    data[1] = value;
    HAL_I2C_Master_Transmit(&hi2c2, OLED_I2C_ADDRESS, data, 2, HAL_MAX_DELAY);
}

void OLED_Send_Command(uint8_t cmd)
{
    OLED_Write(cmd, 0x00);
}

void OLED_Send_Data(uint8_t data)
{
    OLED_Write(data, 0x40);
}

